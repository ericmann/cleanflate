//! `oracle generate`: builds the conformance corpus into
//! `testdata/generated/` and checks/writes `testdata/MANIFEST.json`
//! (SPEC S4, PLAN.md P1-03).

use std::collections::{HashMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};

use crate::ffi::{self, DeflateParams};
use crate::inputs::Input;
use crate::manifest::{self, DictionaryRecord, Manifest, ManifestEntry};
use crate::matrix::{self, entries, inputs_for_tier, CorpusTier, EntrySpec};

/// Outcome of a generate/check run.
#[derive(Debug, Default)]
pub struct Report {
    /// Entries whose file already existed with a matching hash (check
    /// mode) or that were freshly written (both modes).
    pub skipped: usize,
    /// Entries generated (written to disk) this run.
    pub generated: usize,
    /// Mismatches, missing manifest entries or a zlib_version difference,
    /// collected so a single run reports everything wrong at once.
    pub problems: Vec<String>,
}

fn input_map(inputs: &[Input]) -> HashMap<&str, &Input> {
    inputs.iter().map(|i| (i.id.as_str(), i)).collect()
}

fn dictionary_record(path: &Path) -> Result<DictionaryRecord, String> {
    let bytes =
        fs::read(path).map_err(|e| format!("reading dictionary {}: {e}", path.display()))?;
    Ok(DictionaryRecord {
        input: path.to_string_lossy().replace('\\', "/"),
        len: bytes.len(),
        sha256: manifest::sha256_hex(&bytes),
    })
}

/// Compress `spec` against `inputs` and return the generated bytes plus
/// its would-be manifest entry. Does not touch disk.
fn build(
    spec: &EntrySpec,
    inputs: &HashMap<&str, &Input>,
) -> Result<(Vec<u8>, ManifestEntry), String> {
    let input = inputs
        .get(spec.input_id.as_str())
        .ok_or_else(|| format!("{}: unknown input id {}", spec.id, spec.input_id))?;
    let input_bytes = input.bytes();

    let dictionary = match &spec.dictionary {
        Some(p) => {
            Some(fs::read(p).map_err(|e| format!("reading dictionary {}: {e}", p.display()))?)
        }
        None => None,
    };

    let params = DeflateParams {
        level: spec.level,
        strategy: spec.strategy,
        window_bits: spec.window_bits,
        mem_level: spec.mem_level,
        framing: spec.framing,
    };

    let output = ffi::deflate_bytes(&input_bytes, &params, dictionary.as_deref())
        .map_err(|e| format!("{}: deflate failed: {e:?}", spec.id))?;

    let dictionary_record = match &spec.dictionary {
        Some(p) => Some(dictionary_record(p)?),
        None => None,
    };

    let entry = ManifestEntry {
        id: spec.id.clone(),
        tier: matrix::tier_token(spec.tier).to_string(),
        input: input.manifest_source(),
        input_sha256: manifest::sha256_hex(&input_bytes),
        input_len: input_bytes.len(),
        framing: manifest::framing_token(spec.framing).to_string(),
        level: spec.level,
        strategy: manifest::strategy_token(spec.strategy).to_string(),
        window_bits: spec.window_bits,
        mem_level: spec.mem_level,
        dictionary: dictionary_record,
        path: spec.relative_path.clone(),
        sha256: manifest::sha256_hex(&output),
        len: output.len(),
    };

    Ok((output, entry))
}

fn tiers_covered(tier: CorpusTier) -> &'static [&'static str] {
    match tier {
        CorpusTier::Quick => &["synthetic", "canterbury"],
        CorpusTier::Full => &["synthetic", "canterbury", "silesia"],
    }
}

/// Check that Silesia's inputs are present under `corpora_root` when
/// `tier` is `Full`.
fn require_silesia(tier: CorpusTier, corpora_root: &Path) -> Result<(), String> {
    if tier == CorpusTier::Full && crate::inputs::silesia_inputs(corpora_root).is_empty() {
        return Err(
            "Silesia corpus missing: run tools/cleanroom/fetch-corpora.sh silesia".to_string(),
        );
    }
    Ok(())
}

/// `--write-manifest`: (re)generate every entry for `tier`, write it to
/// `out_dir`, and replace `tier`'s entries in the manifest at
/// `manifest_path`, keeping entries for tiers this run does not cover.
pub fn write_manifest(
    tier: CorpusTier,
    out_dir: &Path,
    manifest_path: &Path,
    corpora_root: &Path,
) -> Result<Report, String> {
    require_silesia(tier, corpora_root)?;

    let inputs = inputs_for_tier(tier, corpora_root);
    let lookup = input_map(&inputs);
    let specs = entries(&inputs, corpora_root);

    let mut report = Report::default();
    let mut new_entries = Vec::with_capacity(specs.len());
    for spec in &specs {
        let (bytes, entry) = build(spec, &lookup)?;
        let path = out_dir.join(&spec.relative_path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("creating {}: {e}", parent.display()))?;
        }
        fs::write(&path, &bytes).map_err(|e| format!("writing {}: {e}", path.display()))?;
        report.generated += 1;
        new_entries.push(entry);
    }

    let covered: HashSet<&str> = tiers_covered(tier).iter().copied().collect();
    let mut kept: Vec<ManifestEntry> = if manifest_path.is_file() {
        Manifest::load(manifest_path)?
            .entries
            .into_iter()
            .filter(|e| !covered.contains(e.tier.as_str()))
            .collect()
    } else {
        Vec::new()
    };
    kept.extend(new_entries);

    let manifest = Manifest::new(ffi::zlib_version(), kept);
    manifest.save(manifest_path)?;

    Ok(report)
}

/// Check mode: for every entry `tier` covers, skip it if the file on disk
/// already matches the manifest's recorded sha256. A file present with a
/// different sha256 is reported as a mismatch (tampering/drift), not
/// silently overwritten. A missing file is generated fresh and written,
/// but only if the freshly generated sha matches the manifest (a mismatch
/// there means the manifest itself is stale). Collects every problem
/// (mismatch, missing manifest entry, zlib_version difference) instead of
/// stopping at the first.
pub fn check(
    tier: CorpusTier,
    out_dir: &Path,
    manifest_path: &Path,
    corpora_root: &Path,
) -> Result<Report, String> {
    require_silesia(tier, corpora_root)?;

    let manifest = Manifest::load(manifest_path)?;
    let mut report = Report::default();

    let current_zlib = ffi::zlib_version();
    if manifest.zlib_version != current_zlib {
        report.problems.push(format!(
            "zlib_version differs: manifest has {}, this build has {current_zlib}",
            manifest.zlib_version
        ));
    }

    let inputs = inputs_for_tier(tier, corpora_root);
    let lookup = input_map(&inputs);
    let specs = entries(&inputs, corpora_root);

    for spec in &specs {
        let recorded = match manifest.find(&spec.id) {
            Some(e) => e,
            None => {
                report
                    .problems
                    .push(format!("missing manifest entry: {}", spec.id));
                continue;
            }
        };

        let path = out_dir.join(&spec.relative_path);
        if let Ok(existing) = fs::read(&path) {
            let existing_sha = manifest::sha256_hex(&existing);
            if existing_sha == recorded.sha256 {
                report.skipped += 1;
                continue;
            }
            // The file is present but does not match the manifest: treat
            // this as tampering/drift, the same way sources-check.sh
            // treats a hash mismatch on an already-downloaded file --
            // report it, do not silently overwrite it.
            report.problems.push(format!(
                "sha256 mismatch for {}: manifest has {}, file on disk has {existing_sha}",
                spec.id, recorded.sha256
            ));
            continue;
        }

        // File is missing: generate it fresh and require the freshly
        // generated sha to match the manifest (a mismatch here means the
        // manifest itself is stale, e.g. the generator or this build's
        // zlib changed).
        let (bytes, entry) = match build(spec, &lookup) {
            Ok(v) => v,
            Err(e) => {
                report.problems.push(e);
                continue;
            }
        };
        if entry.sha256 != recorded.sha256 {
            report.problems.push(format!(
                "sha256 mismatch for {}: manifest has {}, generated {}",
                spec.id, recorded.sha256, entry.sha256
            ));
            continue;
        }

        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("creating {}: {e}", parent.display()))?;
        }
        fs::write(&path, &bytes).map_err(|e| format!("writing {}: {e}", path.display()))?;
        report.generated += 1;
    }

    Ok(report)
}

/// Default output directory: `testdata/generated`.
pub fn default_out_dir() -> PathBuf {
    PathBuf::from("testdata/generated")
}

/// Default manifest path: `testdata/MANIFEST.json`.
pub fn default_manifest_path() -> PathBuf {
    PathBuf::from("testdata/MANIFEST.json")
}

/// Default corpora root: `testdata/corpora`.
pub fn default_corpora_root() -> PathBuf {
    PathBuf::from("testdata/corpora")
}
